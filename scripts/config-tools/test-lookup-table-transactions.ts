import assert from 'node:assert/strict';
import fs from 'node:fs';
import { lookupDraftSignature, prepareLookupTableCommit } from '../../src/configStudio/lookupTableTransaction';
import { renameLookupTable } from '../../src/configStudio/lookupTables';
import type { ConfigPackageV3 } from '../../src/configStudio/types';

const baseline: ConfigPackageV3 = JSON.parse(fs.readFileSync('src/configStudio/defaults/r10-r6.config.json', 'utf8'));
const added = structuredClone(baseline);
added.lookupTables!.push({ id: 'temporary-table', label: { zh: 'Temporary', en: '' }, valueType: 'string', functionKind: 'none', rows: [] });
assert.notEqual(lookupDraftSignature(added), lookupDraftSignature(baseline));
added.lookupTables!.pop();
assert.equal(lookupDraftSignature(added), lookupDraftSignature(baseline), 'add then delete returns to clean state');
const edited = structuredClone(baseline);
edited.lookupTables![0].label.zh = 'Changed table';
const concurrent = structuredClone(baseline);
concurrent.workflows[0].label.zh = 'Independent workflow save';
const merged = prepareLookupTableCommit(concurrent, { baseline, value: edited });
assert.equal(merged.workflows[0].label.zh, concurrent.workflows[0].label.zh);
assert.equal(merged.lookupTables![0].label.zh, 'Changed table');
const conflict = structuredClone(concurrent);
conflict.lookupTables![0].rows.reverse();
assert.throws(() => prepareLookupTableCommit(conflict, { baseline, value: edited }), /活动版本/);
const referenced = structuredClone(baseline);
referenced.nodes[0].fields[0].optionsTableId = 'teleport-hubs';
const renamed = renameLookupTable(referenced, 'teleport-hubs', 'renamed-hubs');
const otherEdit = structuredClone(referenced);
otherEdit.nodes[0].fields[0].labels.en = 'Independent field label';
const afterRename = prepareLookupTableCommit(otherEdit, { baseline: referenced, value: renamed });
assert.equal(afterRename.nodes[0].fields[0].optionsTableId, 'renamed-hubs');
assert.equal(afterRename.nodes[0].fields[0].labels.en, 'Independent field label');
otherEdit.nodes[0].fields[0].optionsTableId = 'road-travel-modes';
assert.throws(() => prepareLookupTableCommit(otherEdit, { baseline: referenced, value: renamed }), /引用已变化/);
assert.equal(referenced.nodes[0].fields[0].optionsTableId, 'teleport-hubs', 'baseline remains immutable');
console.log('lookup-table-transactions: clean reversal, independent table save, concurrent unrelated edits, table conflicts and atomic reference rename passed');
