import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {migratePackageToContract} from '../../src/configStudio/contractMigration';
import {validateConfigPackage} from '../../src/configStudio/runtime';
import {buildConfigPackageArchive} from '../../src/configStudio/package';
const hash=(value:Buffer)=>createHash('sha256').update(value).digest('hex');
const pointer=JSON.parse(fs.readFileSync(process.argv[2]??'../../outputs/c22-generation-20261125/production-current.json','utf8'));
const source=path.resolve(process.argv[3]??'public'+pointer.configUrl),out=path.resolve(process.argv[4]??'../../outputs/c22-generation-20261125/candidate');
const bytes=fs.readFileSync(source),base=JSON.parse(bytes.toString('utf8'));
if(hash(bytes)!==pointer.configSha256||base.revision!==pointer.revision||base.contractRevision!==21)throw Error('c22 baseline identity mismatch');
const migrated=migratePackageToContract(base,22),config=migrated.config,report=validateConfigPackage(config);
fs.mkdirSync(out,{recursive:true});
fs.writeFileSync(path.join(out,'validation.json'),JSON.stringify(report,null,2)+'\n');
if(!report.valid)throw Error(JSON.stringify(report.issues.filter(i=>i.severity==='error').slice(0,20)));
const body=Buffer.from(JSON.stringify(config,null,2)+'\n'),archive=Buffer.from(await(await buildConfigPackageArchive(config,report)).arrayBuffer());
fs.writeFileSync(path.join(out,'candidate.config.json'),body);fs.writeFileSync(path.join(out,'c22-ria-review.cairn-config.zip'),archive);
fs.writeFileSync(path.join(out,'migration.json'),JSON.stringify(migrated.report,null,2)+'\n');
const manifest={taskId:'c22-generation-20261125',base:pointer,candidate:{contractRevision:22,revision:config.revision,sha256:hash(body),archiveSha256:hash(archive),nodes:config.nodes.length,workflows:config.workflows.length},productionWrites:false};
fs.writeFileSync(path.join(out,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');console.log(JSON.stringify(manifest.candidate));
