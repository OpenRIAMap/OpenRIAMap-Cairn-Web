import assert from 'node:assert/strict';
import fs from 'node:fs';
import {migratePackageToC16,migrateContract} from '../../src/configStudio/contractMigration';
import {validateConfigPackage} from '../../src/configStudio/runtime';
import {externalBindingIssues,externalRolePaths,resolveExternalReference} from '../../src/configStudio/externalBindings';
import {validateNativeStructure} from '../../src/configStudio/nativeContractValidation';
import type {ConfigPackageV3} from '../../src/configStudio/types';

const identity=JSON.parse(fs.readFileSync('public/configuration/current.json','utf8'));
const original=JSON.parse(fs.readFileSync('public'+identity.configUrl,'utf8')) as ConfigPackageV3,before=JSON.stringify(original);
const {config,report}=migratePackageToC16(original);
assert.equal(config.contractRevision,16);assert.equal(JSON.stringify(original),before,'input is immutable');
assert.deepEqual(config.workflows.filter(w=>w.mode==='composed'),original.workflows.filter(w=>w.mode==='composed'));
assert.deepEqual(externalBindingIssues(config),[]);
const validation=validateConfigPackage(config);
assert.equal(validation.valid,true,JSON.stringify(validation.issues.filter(i=>i.severity==='error'),null,2));
assert.ok(report.changes.length>0);assert.equal(report.steps.at(-1),'c15 → c16');
const railway=config.workflows.find(w=>w.external?.componentKey==='railwayWorkflow')!,trade=config.workflows.find(w=>w.external?.componentKey==='tradePointWorkflow')!,editor=config.workflows.find(w=>w.external?.componentKey==='tradePointEditor')!;
assert.deepEqual(externalRolePaths(config,railway,'railLine'),[{class:'RIL',kind:'RLE'}]);
assert.deepEqual(resolveExternalReference(config,editor,'landUnit'),resolveExternalReference(config,trade,'landUnit'));
const renamed=structuredClone(config),newLine=structuredClone(renamed.nodes.find(n=>n.path.class==='RIL'&&n.path.kind==='RLE')!);
newLine.nodeId='new-rail';newLine.path={class:'CUSTOM',kind:'TRACK'};renamed.nodes.push({...newLine,nodeId:'new-root',path:{class:'CUSTOM'},fields:[],geometryProfiles:{},children:[newLine.nodeId]},newLine);
const routed=renamed.workflows.find(w=>w.id===railway.id)!;
routed.external!.roleBindings![0].classificationGroup.selectors[0].path=newLine.path;
assert.deepEqual(externalRolePaths(renamed,routed,'railLine'),[newLine.path]);
assert.equal(externalBindingIssues(renamed).filter(i=>i.path.includes(railway.id)).length,0,'role dispatch is independent of taxonomy code');
const missing=structuredClone(config);missing.workflows.find(w=>w.id===railway.id)!.external!.roleBindings=[];
assert.ok(externalBindingIssues(missing).some(i=>i.message.includes('唯一')));
const cycle=structuredClone(config),cyclic=cycle.workflows.find(w=>w.id===trade.id)!;
cyclic.external!.referenceBindings![0]={bindingId:'landUnit',source:{workflowId:trade.id,bindingId:'landUnit'}};
assert.throws(()=>resolveExternalReference(cycle,cyclic,'landUnit'),/循环/);
assert.ok(externalBindingIssues(cycle).some(i=>i.message.includes('循环')));
const wrongType=structuredClone(config);wrongType.nodes.find(n=>n.path.class==='RIL'&&n.path.kind==='PLF')!.fields.find(f=>f.key==='lines')!.type='string';
assert.ok(externalBindingIssues(wrongType).some(i=>i.path.endsWith('/lines')));
const fragment=migrateContract({contractRevision:15,workflow:original.workflows.find(w=>w.id===railway.id)!},16,'workflow',original);
assert.ok(fragment.document.workflow.external?.roleBindings?.length);
const rejected=structuredClone(config);rejected.contractRevision=15;
assert.ok(validateNativeStructure(rejected).some(i=>i.message.includes('c16')));
console.log('c16 bindings: migration, preserved ordinary content, arbitrary taxonomy, missing role, cycle, field type, fragment and version guards passed');

const incomplete=structuredClone(config);incomplete.nodes.find(node=>node.path.class==='RIL'&&node.path.kind==='RLE')!.fields.find(field=>field.key==='direction')!.optionTable!.rows.pop();assert(externalBindingIssues(incomplete).some(issue=>issue.message.includes('0–7')));
