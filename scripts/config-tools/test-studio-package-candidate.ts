import assert from 'node:assert/strict';
import fs from 'node:fs';
import { migrateConfigToR12 } from '../../src/configStudio/r12Migration';
import { prepareEngineCommit } from '../../src/configStudio/engineTransaction';
import { validateStudioModule } from '../../src/configStudio/studioModuleValidation';
import { validateConfigPackage } from '../../src/configStudio/runtime';
import { recoverPackageCandidate, type StudioEditingSession } from '../../src/configStudio/studioSession';
import type { ConfigPackageV3 } from '../../src/configStudio/types';

const baseline = JSON.parse(fs.readFileSync('src/configStudio/defaults/r11-r7.config.json', 'utf8')) as ConfigPackageV3;
const config = migrateConfigToR12(baseline).config;
assert(validateConfigPackage(config).valid);
const editedEngine = structuredClone(config.engine!);
editedEngine.contextView.activationRadiusPx += 1;
const changedOther = structuredClone(config);
changedOther.displayName.zh += ' engine transaction check';
const engineCommit = prepareEngineCommit(changedOther, { baseline: config.engine, value: editedEngine });
assert.deepEqual(engineCommit.engine, editedEngine);
assert.deepEqual(engineCommit.nodes, changedOther.nodes);
assert.deepEqual(engineCommit.application, changedOther.application);
assert.deepEqual(engineCommit.workflows, changedOther.workflows);
assert.deepEqual(engineCommit.lookupTables, changedOther.lookupTables);
assert.equal(engineCommit.displayName.zh, changedOther.displayName.zh);
const concurrent = structuredClone(config);
concurrent.engine!.contextView.activationRadiusPx += 2;
assert.throws(() => prepareEngineCommit(concurrent, { baseline: config.engine, value: editedEngine }), /已被其他编辑更新/);

const broken = structuredClone(config);
broken.application!.preferences.search.homepageLimit = 0;
const workflow = broken.workflows.find(w => w.mode === 'composed' && w.editor?.enabled)!;
assert(workflow);
workflow.editor!.backfill = [{ slot: '__missing_slot', target: 'Name' }];
const errors = validateConfigPackage(broken).issues.filter(i => i.severity === 'error');
assert(errors.some(i => i.path.startsWith('application/preferences')), JSON.stringify(errors));
assert(errors.some(i => i.path.startsWith('workflows/' + workflow.id)), JSON.stringify(errors));
assert(!errors.some(i => i.code === 'native-contract-structure-invalid'), 'semantic import problems must remain editable as a candidate');
assert(validateStudioModule(broken, [], ['engine']).valid, 'an unrelated workflow/application error must not block staging a repaired engine');
assert(!validateStudioModule(broken, []).valid, 'the same package must still fail an ordinary active save');
assert(!validateStudioModule(broken, [], ['application/preferences']).valid);
const fixedWorkflow = structuredClone(broken);
delete fixedWorkflow.workflows.find(w => w.id === workflow.id)!.editor!.backfill;
assert(validateStudioModule(fixedWorkflow, [], ['workflows/' + workflow.id]).valid);
assert(!validateConfigPackage(fixedWorkflow).valid);
const badNode = structuredClone(config);
const owner = badNode.nodes.find(n => n.fields.length)!;
owner.fields[0].optionsTableId = '__missing_table';
assert(!validateStudioModule(badNode, [], ['nodes/' + owner.nodeId]).valid, 'a local field reference error must still block staging its own category');
const badTables = structuredClone(config);
badTables.lookupTables!.push(structuredClone(badTables.lookupTables![0]));
assert(!validateStudioModule(badTables, [], ['lookupTables']).valid, 'duplicate tables must block their own module');
const fixedPreferences = structuredClone(broken);
fixedPreferences.application!.preferences.search.homepageLimit = config.application!.preferences.search.homepageLimit;
assert(validateStudioModule(fixedPreferences, [], ['application/preferences']).valid, 'repaired preferences can stage while a workflow remains invalid');
assert(!validateConfigPackage(fixedPreferences).valid, 'a partially repaired candidate cannot become active');
delete fixedPreferences.workflows.find(w => w.id === workflow.id)!.editor!.backfill;
assert(validateConfigPackage(fixedPreferences).valid);
const schemaBroken = structuredClone(config) as any;
schemaBroken.nodes[0].fields = 'not an array';
assert(!validateStudioModule(schemaBroken, [], ['engine']).valid, 'structural corruption cannot bypass a module gate');

const oldSession: StudioEditingSession = { baseline, draft: config, tree: null, selectedId: '', editing: true };
const recovered = recoverPackageCandidate(oldSession)!;
assert.equal(recovered.source, 'recovery');
assert.equal(recovered.config.contractRevision, 12);
assert.equal(recovered.baseline.contractRevision, 11);
assert.equal(recoverPackageCandidate({ ...oldSession, packageCandidate: { ...recovered, source: 'import' }, draft: null })!.source, 'import');
assert.equal(recoverPackageCandidate({ ...oldSession, draft: null }), null);
assert.equal(baseline.contractRevision, 11);
assert.deepEqual(config.engine, changedOther.engine, 'module staging must not mutate its original configuration');
console.log('Studio package candidate: independent engine merge/conflicts, scoped staging with multi-module errors, full final gate and legacy recovery passed.');
