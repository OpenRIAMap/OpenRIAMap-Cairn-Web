import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import JSZip from 'jszip';
import {buildConfigPackageArchive} from '../../src/configStudio/package';
import {validateConfigPackage} from '../../src/configStudio/runtime';
import {verifyPublishedMirror} from './productionMirror';
import {readFormalRelayContext} from '../relay/formal-configuration-context.mjs';
const hash=(body:Uint8Array)=>createHash('sha256').update(body).digest('hex');
const config=JSON.parse(await fs.readFile('src/configStudio/defaults/r11-r7.config.json','utf8'));
config.revision=8;config.displayName.en+=' next release';
const archive=new Uint8Array(await(await buildConfigPackageArchive(config,validateConfigPackage(config))).arrayBuffer()),zip=await JSZip.loadAsync(archive);
const raw=await zip.file('config.json')!.async('nodebuffer'),manifest=await zip.file('manifest.json')!.async('nodebuffer');
const identity={releaseId:'config-future-current-test',packageId:config.packageId,projectId:config.projectId,revision:8,contractRevision:11,configSha256:hash(raw),manifestSha256:hash(manifest),configUrl:`/configuration/releases/${hash(raw)}/config.json`};
const root=path.resolve('node_modules/.cache/config-production-mirror-test'),folder=path.join(root,'configuration/releases',identity.configSha256);
await fs.mkdir(folder,{recursive:true});
for(const [name,body] of [['config.json',raw],['manifest.json',manifest],['package.zip',archive],['release.json',JSON.stringify({schemaVersion:'cairnmap.configuration-release.v1',identity,archiveSha256:hash(archive)})]] as const)await fs.writeFile(path.join(folder,name),body);
const pointer=path.join(root,'configuration/current.json');await fs.writeFile(pointer,JSON.stringify(identity));
assert.equal((await verifyPublishedMirror(root)).identity.revision,8,'a later legitimate active mirror must pass the deployment build');
assert.equal(readFormalRelayContext(config.projectId,{publicRoot:root}).configuration.revision,8,'CLI tasks read the updated published mirror');
await fs.writeFile(pointer,JSON.stringify({...identity,configUrl:'https://attacker.example/config.json'}));
await assert.rejects(()=>verifyPublishedMirror(root),/identity/);
await fs.writeFile(pointer,JSON.stringify({...identity,revision:9}));
await assert.rejects(()=>verifyPublishedMirror(root),/package/);
await fs.writeFile(pointer,JSON.stringify(identity));
console.log('production-mirror: later r8 current passes independently of immutable r7 seed; raw hashes, archive equality, revision identity, controlled URLs and CLI advancement verified');
