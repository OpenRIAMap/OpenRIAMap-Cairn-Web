import assert from 'node:assert/strict';
import { PointSequence, applyPointEdit, undoPointEdit, type InputPoint } from '../../src/components/Mapping/tools/pointSequence';
import { newShape, sampleShape, shapeVertices, worldShapePoints, type ShapeKind } from '../../src/components/Mapping/tools/shapeInputGeometry';
const point = (x: number): InputPoint => ({ x, z: x * 2, y: -64 });
const sequence = new PointSequence();
sequence.reset([point(0), point(10), point(20)]); sequence.select(0);
const before = sequence.snapshot();
sequence.append([point(1), point(2)], false); const two = sequence.snapshot();
sequence.append([point(3)], false);
assert.deepEqual(sequence.points.map(p => p.x), [0, 1, 2, 3, 10, 20]);
sequence.restore(two); assert.equal(sequence.index, 2);
sequence.restore(before); assert.equal(sequence.index, 0);
sequence.append([point(4)], false); assert.deepEqual(sequence.points.map(p => p.x), [0, 4, 10, 20]);
sequence.stop(); sequence.restore(two); assert.equal(sequence.active, false, 'history never re-enables a stopped input mode');
sequence.append([point(30)], false); assert.equal(sequence.points[sequence.points.length - 1].x, 30);
sequence.select(2); sequence.sync([point(100), point(200)]); assert.equal(sequence.active, false, 'replacement cannot bind an old index');
sequence.reset([point(0), point(10), point(20), point(0)]); sequence.select(2); sequence.append([point(25)], true);
assert.deepEqual(sequence.points.map(p => p.x), [0, 10, 20, 25, 0], 'closed ring insertion goes before its duplicated closing coordinate');
const h0 = { points: [point(1), point(2), point(3)], undo: [], redo: [] };
let history = applyPointEdit(h0, [point(1), point(4), point(3)]);
history = applyPointEdit(history, [point(1), point(4), point(5), point(3)]);
history = applyPointEdit(history, [point(1), point(5), point(3)]);
for (let i = 0; i < 3; i++) history = undoPointEdit(history);
assert.deepEqual(history.points, h0.points);
for (let i = 0; i < 3; i++) history = undoPointEdit(history, true);
assert.deepEqual(history.points, [point(1), point(5), point(3)]);
assert.equal(applyPointEdit(history, history.points), history, 'no-op must preserve redo and undo');
for (const kind of ['circle', 'ellipse', 'square', 'rectangle', 'polygon'] as ShapeKind[]) {
  const shape = { ...newShape(kind, { x: 100, z: 200, y: -62 }, 10, 5), angle: 90, width: 20, height: 12, rx: 14, rz: 7 };
  const count = kind === 'polygon' ? 13 : 32;
  const points = sampleShape(shape, count);
  assert.equal(points.length, count); assert(points.every(p => p.y === -62));
  const line = sampleShape(shape, count, true); assert.equal(line.length, count + 1); assert.deepEqual(line[0], line[line.length - 1]);
  if (!['circle', 'ellipse'].includes(kind)) for (const corner of worldShapePoints(shape, shapeVertices(shape))) assert(points.some(p => Math.hypot(p.x - corner.x, p.z - corner.z) < .08), `${kind}: preserve every corner`);
}
const invalid = newShape('polygon', { x: 0, z: 0 }, 10, 4);
invalid.vertices = [{ x: -5, z: -5 }, { x: 5, z: 5 }, { x: -5, z: 5 }, { x: 5, z: -5 }];
assert.throws(() => sampleShape(invalid, 8), /面积|自交/);
assert.throws(() => sampleShape(newShape('circle', { x: 0, z: 0 }, .01), 32), /重复点/);
assert.throws(() => sampleShape(newShape('polygon', { x: 0, z: 0 }, 10, 6), 5), /数量/);
assert.throws(() => sampleShape(newShape('circle', { x: NaN, z: 0 }), 32), /有效数字/);
console.log('Control-point mixed history, stable insertion identities, ring closure and shape sampling regressions passed.');
